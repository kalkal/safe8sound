import { describe, expect, it } from 'vitest';
import { ToolErrorSchema } from '../src/tool-error.js';
import { callTool, makeHandler, post } from './helpers.js';

interface ToolResult {
  isError?: boolean;
  content: Array<{ type: string; text: string }>;
  structuredContent?: Record<string, unknown>;
}

async function toolResult(res: Response): Promise<ToolResult> {
  expect(res.status).toBe(200);
  const body = (await res.json()) as { result?: ToolResult; error?: unknown };
  expect(body.error).toBeUndefined();
  return body.result as ToolResult;
}

describe('tools/list', () => {
  it('advertises every tool with object input and output JSON Schemas generated by Zod v4', async () => {
    const { handler } = makeHandler();
    const res = await post(handler, { jsonrpc: '2.0', id: 1, method: 'tools/list', params: {} });
    const body = (await res.json()) as {
      result: { tools: Array<{ name: string; inputSchema: Record<string, unknown>; outputSchema: Record<string, unknown> }> };
    };
    const tool = body.result.tools.find((t) => t.name === 'get_reserve_status');
    expect(tool).toBeDefined();
    expect(tool?.inputSchema.type).toBe('object');
    expect(tool?.inputSchema.required).toEqual(['homeId']);
    expect(tool?.outputSchema.type).toBe('object');
    // The output schema also admits the error envelope, so clients that validate
    // structuredContent on isError results do not reject tool errors.
    expect(JSON.stringify(tool?.outputSchema)).toContain('retryable');
  });
});

describe('tools/call get_reserve_status', () => {
  it('returns structuredContent and a text summary on success', async () => {
    const { handler } = makeHandler();
    const result = await toolResult(await post(handler, callTool('get_reserve_status', { homeId: 'home-demo' })));
    expect(result.isError).toBeFalsy();
    expect(result.structuredContent).toEqual({
      homeId: 'home-demo',
      stateOfChargePct: 62,
      reserveHours: 9.5,
      dataOrigin: 'simulated',
      ageSeconds: 60,
    });
    expect(result.content[0]?.type).toBe('text');
    expect(result.content[0]?.text.length).toBeGreaterThan(0);
  });

  it('returns isError + home_not_found for an unknown home', async () => {
    const { handler } = makeHandler();
    const result = await toolResult(await post(handler, callTool('get_reserve_status', { homeId: 'nowhere' })));
    expect(result.isError).toBe(true);
    expect(ToolErrorSchema.parse(result.structuredContent)).toMatchObject({
      code: 'home_not_found',
      category: 'not_found',
      retryable: false,
    });
    expect(result.content[0]?.text).toBe((result.structuredContent as { message: string }).message);
  });

  it('returns isError + home_data_stale (retryable, with retryAfterMs) for stale data', async () => {
    const { handler } = makeHandler();
    const result = await toolResult(await post(handler, callTool('get_reserve_status', { homeId: 'home-stale' })));
    expect(result.isError).toBe(true);
    expect(ToolErrorSchema.parse(result.structuredContent)).toMatchObject({
      code: 'home_data_stale',
      category: 'dependency_unavailable',
      retryable: true,
      retryAfterMs: 60_000,
      details: { ageSeconds: 1200 },
    });
  });

  it('returns isError + invalid_arguments (validation) when the input breaks the schema', async () => {
    const { handler } = makeHandler();
    const result = await toolResult(await post(handler, callTool('get_reserve_status', { homeId: 42 })));
    expect(result.isError).toBe(true);
    const err = ToolErrorSchema.parse(result.structuredContent);
    expect(err).toMatchObject({ code: 'invalid_arguments', category: 'validation', retryable: false });
    expect(err.details).toHaveProperty('issues');
  });

  it('treats missing arguments as an empty object and reports the missing field', async () => {
    const { handler } = makeHandler();
    const res = await post(handler, { jsonrpc: '2.0', id: 3, method: 'tools/call', params: { name: 'get_reserve_status' } });
    const result = await toolResult(res);
    expect(result.structuredContent).toMatchObject({ code: 'invalid_arguments' });
  });
});

describe('tools/call failure paths', () => {
  it('answers an unknown tool with a JSON-RPC protocol error (-32602)', async () => {
    const { handler } = makeHandler();
    const res = await post(handler, callTool('no_such_tool', {}));
    const body = (await res.json()) as { error?: { code: number; message: string }; result?: unknown };
    expect(body.result).toBeUndefined();
    expect(body.error?.code).toBe(-32602);
  });

  it('turns a thrown exception into isError + unexpected_error, without leaking internals, and logs it once', async () => {
    const { handler, logs } = makeHandler();
    const res = await post(handler, callTool('explode', {}), { 'x-correlation-id': '0b6f3c1e-5a0d-4f7e-9d0a-2b1c3d4e5f60' });
    const result = await toolResult(res);
    expect(result.isError).toBe(true);
    expect(result.structuredContent).toMatchObject({ code: 'unexpected_error', category: 'internal', retryable: false });
    expect(JSON.stringify(result)).not.toContain('/secret/path');
    const errors = logs.filter((l) => l.level === 'error');
    expect(errors).toHaveLength(1);
    expect(errors[0]).toMatchObject({
      code: 'unexpected_error',
      category: 'internal',
      correlationId: '0b6f3c1e-5a0d-4f7e-9d0a-2b1c3d4e5f60',
    });
  });

  it('turns an output that breaks its own schema into isError + output_schema_violation (internal)', async () => {
    const { handler, logs } = makeHandler();
    const result = await toolResult(await post(handler, callTool('bad_output', {})));
    expect(result.isError).toBe(true);
    expect(result.structuredContent).toMatchObject({ code: 'output_schema_violation', category: 'internal' });
    expect(logs.some((l) => l.code === 'output_schema_violation')).toBe(true);
  });

  it('logs only the categories the error log keeps (not not_found or validation)', async () => {
    const { handler, logs } = makeHandler();
    await post(handler, callTool('get_reserve_status', { homeId: 'nowhere' }));
    expect(logs.filter((l) => l.level === 'error')).toHaveLength(0);
    await post(handler, callTool('get_reserve_status', { homeId: 'home-stale' }));
    expect(logs.filter((l) => l.code === 'home_data_stale')).toHaveLength(1);
  });
});
