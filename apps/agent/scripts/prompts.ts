import { readdir, readFile, writeFile } from 'node:fs/promises';

// Builds src/prompts.generated.ts from prompts/system.<version>.md (G1a): the agent is bundled to one CJS
// file for AgentCore, where reading a file next to the code no longer works. The .md stays the source
// people review; a test fails when the generated module is stale.

const dir = new URL('../prompts/', import.meta.url);
const files = (await readdir(dir)).filter((f) => /^system\.v\d+\.md$/.test(f)).sort();
const entries: string[] = [];
for (const file of files) {
  const version = /^system\.(v\d+)\.md$/.exec(file)?.[1] ?? '';
  const text = (await readFile(new URL(file, dir), 'utf8')).trim();
  entries.push(`  ${version}: ${JSON.stringify(text)},`);
}
const out = `// Generated by scripts/prompts.ts from prompts/system.<version>.md. Do not edit: run \`pnpm --filter @cold-reserve/agent prompts\`.
export const SYSTEM_PROMPTS = {
${entries.join('\n')}
} as const;
`;
await writeFile(new URL('../src/prompts.generated.ts', import.meta.url), out);
console.log(`prompts: ${String(files.length)} system prompt(s) written to src/prompts.generated.ts`);
